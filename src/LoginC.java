    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = USER.getText().trim();
        String password = new String(Passw.getPassword()).trim();

        // Check if username or password is empty
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Sorry, the username or password cannot be empty.", "Login Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        boolean isValid = false;

        try {
            BufferedReader reader = new BufferedReader(new FileReader("user.txt"));
            String line;

            // Read each line from the user.txt file
            while ((line = reader.readLine()) != null) {
                String[] credentials = line.split(";"); // Use semicolon as the delimiter

                // Check if the length of the split array is valid and then match the username and password
                if (credentials.length >= 2 && credentials[0].equals(username) && credentials[1].equals(password)) {
                    isValid = true;
                    break; // Exit the loop if valid credentials are found
                }
            }
            reader.close();
        } catch (IOException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error reading from the user file.", "File Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // After checking all lines, show the appropriate message
        if (isValid) {
            JOptionPane.showMessageDialog(this, "Login Successful!", "Success", JOptionPane.INFORMATION_MESSAGE);
            // Proceed to the MainCustomer page after successful login
            new MainCustomer().setVisible(true); // Show the MainCustomer page
            this.dispose(); // Close the login window
        } else {
            JOptionPane.showMessageDialog(this, "The username or password is wrong, try again!", "Login Error", JOptionPane.ERROR_MESSAGE);
        }// TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

