    private void registerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerActionPerformed
 try {
        String plainConfirmPassword = new String(confirmpassword.getPassword());
        String plainPassword = new String(password.getPassword()); // Convert the password to string
        String newUsername = username.getText(); // Username entered by the user

        // Check if any field is empty
        if (newUsername.isEmpty() || email.getText().isEmpty() || fullname.getText().isEmpty() ||
            plainPassword.isEmpty() || plainConfirmPassword.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Sorry, there is missing data. Please fill in all the options.");
            return; // Stop further execution
        }

        // Check if username already exists
        if (isUsernameTaken(newUsername)) {
            JOptionPane.showMessageDialog(null, "Sorry, the username already exists.");
            return; // Stop further execution
        }

        // Check if password and confirm password match
        if (plainConfirmPassword.equals(plainPassword)) {
            // Create an ArrayList to hold the user data
            ArrayList<String> user = new ArrayList<>();
            user.add(newUsername); // Username
            user.add(plainPassword); // Password
            user.add(email.getText()); // Email
            user.add(fullname.getText()); // Full name

            // Write the data to the file
            try (FileWriter fw = new FileWriter("user.txt", true)) {
                // Append each user's data to the file with proper formatting
                fw.write(String.join(";", user) + "\n");
            }

            JOptionPane.showMessageDialog(null, "Successfully Registered!");
            this.dispose(); // Close the registration form
            new LoginC().setVisible(true); // Open login form
        } else {
            JOptionPane.showMessageDialog(null, "Your confirm password is not the same!");
        }
    } catch (IOException e) {
        System.out.println("Error Exception: " + e.getMessage());
    }

}                                            

// Helper method to check if the username already exists
private boolean isUsernameTaken(String username) {
    try (Scanner scanner = new Scanner(new File("user.txt"))) {
        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            String[] userData = line.split(";"); // Assuming the user data is separated by semicolons
            String existingUsername = userData[0]; // Username is the first field in the data
            if (existingUsername.equals(username)) {
                return true; // Username already exists
            }
        }
    } catch (FileNotFoundException e) {
        System.out.println("User file not found: " + e.getMessage());
    }
    return false; // Username does not exist

    }//GEN-LAST:event_registerActionPerformed

