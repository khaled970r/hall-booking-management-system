    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
 int selectedRow = jTable1.getSelectedRow();  // Get the selected row index

    if (selectedRow == -1) {
        // If no row is selected, show an error message
        JOptionPane.showMessageDialog(this, "Please select a Hall from the table to Book.", "No Hall Selected", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Retrieve data from the selected row
    String hallId = jTable1.getValueAt(selectedRow, 0).toString();
    String hallType = jTable1.getValueAt(selectedRow, 1).toString();
    String bookingRate = jTable1.getValueAt(selectedRow, 2).toString();
    String capacity = jTable1.getValueAt(selectedRow, 3).toString();
    String remarks = jTable1.getValueAt(selectedRow, 8).toString();

    // Retrieve customer details
    String customerusercheck = Usercheck.getText();
    String customerName = Name.getText();
    String customerEmail = Email.getText();
    String customerPhone = phoneNumber.getText();
    String bookingDate = DateBooking.getText();

    // Validate the date format (dd/MM/yyyy) and convert to a Date object
    SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");
    sdf.setLenient(false); // Prevents invalid dates
    Date date;

    try {
        date = sdf.parse(bookingDate); // This will throw ParseException if the date is invalid
    } catch (ParseException e) {
        JOptionPane.showMessageDialog(this, "Please enter the booking date like this format 09/06/2024.", "Invalid Date Format", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Payment method
    String paymentMethod = jCheckBox1.isSelected() ? "Cash" : jCheckBox2.isSelected() ? "Credit Card" : "None";

    // Check if no payment method is selected
    if (paymentMethod.equals("None")) {
        JOptionPane.showMessageDialog(this, "Please select a payment method.", "No Payment Method Selected", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Write booking details to BookedHall.txt
    try (FileWriter writer = new FileWriter("BookedHall.txt", true)) {  // true for appending to the file
        writer.write("Customer User: " + customerusercheck + "\n");
        writer.write("Customer Name: " + customerName + "\n");
        writer.write("Customer Email: " + customerEmail + "\n");
        writer.write("Customer Phone: " + customerPhone + "\n");
        writer.write("Booking Date: " + bookingDate + "\n");
        writer.write("Hall ID: " + hallId + "\n");
        writer.write("Hall Type: " + hallType + "\n");
        writer.write("Booking Rate: " + bookingRate + "\n");
        writer.write("Capacity: " + capacity + "\n");
        writer.write("Start Date: " + jTable1.getValueAt(selectedRow, 4).toString() + "\n");
        writer.write("End Date: " + jTable1.getValueAt(selectedRow, 6).toString() + "\n");
        writer.write("Remarks: " + remarks + "\n");
        writer.write("Payment Method: " + paymentMethod + "\n");
        writer.write("-------------------------------\n");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error writing to BookedHall.txt", "File Error", JOptionPane.ERROR_MESSAGE);
    }

    // Write booking details to HistoryBooking.txt (without Start Date and End Date)
    try (FileWriter historyWriter = new FileWriter("HistoryBooking.txt", true)) {  // true for appending to the file
        historyWriter.write("Customer User: " + customerusercheck + "\n");
        historyWriter.write("Customer Name: " + customerName + "\n");
        historyWriter.write("Customer Email: " + customerEmail + "\n");
        historyWriter.write("Customer Phone: " + customerPhone + "\n");
        historyWriter.write("Booking Date: " + bookingDate + "\n");
        historyWriter.write("Hall ID: " + hallId + "\n");
        historyWriter.write("Hall Type: " + hallType + "\n");
        historyWriter.write("Booking Rate: " + bookingRate + "\n");
        historyWriter.write("Capacity: " + capacity + "\n");
        historyWriter.write("Remarks: " + remarks + "\n");
        historyWriter.write("Payment Method: " + paymentMethod + "\n");
        historyWriter.write("-------------------------------\n");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error writing to HistoryBooking.txt", "File Error", JOptionPane.ERROR_MESSAGE);
    }

    // Check the payment method and redirect accordingly
    if (jCheckBox2.isSelected()) {
        // If credit card selected, redirect to PayPage
        Pay pay = new Pay(); // Ensure this matches the class name
        pay.setVisible(true);
        this.dispose();
    } else if (jCheckBox1.isSelected()) {
        // If cash selected, show success message and redirect to MainCustomer
        JOptionPane.showMessageDialog(this, "Booking successful!", "Success", JOptionPane.INFORMATION_MESSAGE);
        MainCustomer mainCustomer = new MainCustomer();
        mainCustomer.setVisible(true);
        this.dispose();  // Close current window
    }

    }//GEN-LAST:event_jButton5ActionPerformed

    private void jTable1AncestorAdded(javax.swing.event.AncestorEvent evt) {//GEN-FIRST:event_jTable1AncestorAdded
DefaultTableModel model = new DefaultTableModel();
    model.addColumn("Hall ID");
    model.addColumn("Hall Type");
    model.addColumn("Booking Rate");
    model.addColumn("Capacity");
    model.addColumn("Start Date");
    model.addColumn("Start Time");
    model.addColumn("End Date");
    model.addColumn("End Time");
    model.addColumn("Remarks");

    // Open and read the availability_schedule.txt file
    File file = new File("availability_schedule.txt");
    if (file.exists()) {
        try (BufferedReader br = new BufferedReader(new FileReader(file))) {
            String line;

            // Read each line from the file
            while ((line = br.readLine()) != null) {
                // Extract the individual data elements from the line
                String[] data = line.split(", ");
                String hallId = data[0].split(": ")[1].trim();
                String hallType = data[1].split(": ")[1].trim();
                String bookingRate = data[2].split(": ")[1].trim();
                String capacity = data[3].split(": ")[1].trim();
                String startDate = data[4].split(": ")[1].trim();
                String startTime = data[5].split(": ")[1].trim();
                String endDate = data[6].split(": ")[1].trim();
                String endTime = data[7].split(": ")[1].trim();
                String remarks = data[8].split(": ")[1].trim();
                
                // Add row to the model
                model.addRow(new Object[]{hallId, hallType, bookingRate, capacity, startDate, startTime, endDate, endTime, remarks});
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error reading from availability_schedule.txt", "File Error", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "availability_schedule.txt not found!", "File Error", JOptionPane.ERROR_MESSAGE);
    }

    // Set the model to the JTable to display the data
    jTable1.setModel(model);
    
jTable1.getColumnModel().getColumn(0).setPreferredWidth(50);  // Hall ID
jTable1.getColumnModel().getColumn(1).setPreferredWidth(120); // Hall Type
jTable1.getColumnModel().getColumn(2).setPreferredWidth(120); // Booking Rate
jTable1.getColumnModel().getColumn(3).setPreferredWidth(80);  // Capacity
jTable1.getColumnModel().getColumn(4).setPreferredWidth(80);  // Start Date
jTable1.getColumnModel().getColumn(5).setPreferredWidth(80);  // Start Time
jTable1.getColumnModel().getColumn(6).setPreferredWidth(80);  // End Date
jTable1.getColumnModel().getColumn(7).setPreferredWidth(80);  // End Time
jTable1.getColumnModel().getColumn(8).setPreferredWidth(80); 
    }//GEN-LAST:event_jTable1AncestorAdded

