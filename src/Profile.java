private boolean isUserSearched = false;
    private void SearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SearchActionPerformed
   String searchUsername = suernameSearch.getText().trim();  // Get the username from the text field
    File file = new File("user.txt");
    boolean userFound = false;

    try (BufferedReader br = new BufferedReader(new FileReader(file))) {
        String line;
        while ((line = br.readLine()) != null) {
            String[] userDetails = line.split(";");  // Assuming each user detail is separated by semicolons
            if (userDetails.length >= 4 && userDetails[0].equals(searchUsername)) {  // Check if the username matches
                userFound = true;

                // Set the user details into the fields
                Name.setText(userDetails[3]);
                Email.setText(userDetails[2]);
                Passwd.setText(userDetails[1]);
                
                // Clear PasswdC (confirm password) to ensure user enters it manually
               

                // Store the original details for comparison later
                String originalName = userDetails[3];
                String originalEmail = userDetails[2];
                String originalPasswd = userDetails[1];

                isUserSearched = true;
                break;  // Stop the search after finding the user
            }
        }

        if (!userFound) {
            JOptionPane.showMessageDialog(this, "User not found!", "Search Result", JOptionPane.ERROR_MESSAGE);
            isUserSearched = false;  // Reset the flag if no user is found
        }

    } catch (IOException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error reading from the user file.", "File Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_SearchActionPerformed

    private void UbdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UbdateActionPerformed
 if (!isUserSearched) {
        JOptionPane.showMessageDialog(this, "Please search for a user first!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Get data from the text fields
    String newName = Name.getText().trim();
    String newEmail = Email.getText().trim();
    String newPasswd = new String(Passwd.getPassword()).trim(); // Convert char[] to String

    // Check if any field is empty
    if (newName.isEmpty() || newEmail.isEmpty() || newPasswd.isEmpty()) {
        JOptionPane.showMessageDialog(this, "All fields must be filled!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
        String originalName = null;
        String originalEmail = null;

    // Check if any changes were made
    if (newName.equals(originalName) && newEmail.equals(originalEmail) && newPasswd.equals(originalPasswd)) {
        JOptionPane.showMessageDialog(this, "No changes were made to the data!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Ask for confirmation before updating the data
    int response = JOptionPane.showConfirmDialog(this, "Are you sure you want to update the data?", "Confirm Update", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
    
    if (response == JOptionPane.NO_OPTION) {
        // If user selected "No", display the original data again
        Name.setText(originalName);
        Email.setText(originalEmail);
        Passwd.setText((String) originalPasswd);
        return;  // Exit without updating the data
    }

    // Proceed to update the user's data
    String searchUsername = suernameSearch.getText().trim();  // Get the username from the text field
    File file = new File("user.txt");
    boolean userFound = false;

    StringBuilder fileContent = new StringBuilder();  // To store the updated content of the file
    try (BufferedReader br = new BufferedReader(new FileReader(file))) {
        String line;
        while ((line = br.readLine()) != null) {
            String[] userDetails = line.split(";");  // Assuming each user detail is separated by semicolons

            // If the username matches, update the user's details
            if (userDetails.length >= 4 && userDetails[0].equals(searchUsername)) {
                userFound = true;

                // Update the user details in the file (password, email, and name)
                String updatedLine = userDetails[0] + ";" + newPasswd + ";" + newEmail + ";" + newName;
                fileContent.append(updatedLine).append("\n");
            } else {
                // Keep other user details unchanged
                fileContent.append(line).append("\n");
            }
        }
    } catch (IOException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error reading from the user file.", "File Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Write the updated content back to the file
    if (userFound) {
        try (FileWriter fw = new FileWriter(file)) {
            fw.write(fileContent.toString());  // Write the updated file content
            JOptionPane.showMessageDialog(this, "User data updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } catch (IOException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error writing to the user file.", "File Error", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "User not found!", "Update Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_UbdateActionPerformed

