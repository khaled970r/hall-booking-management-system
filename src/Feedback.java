    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       String searchUserId = jTextField1.getText().trim();  // Get user ID from input
        File file = new File("HistoryBooking.txt");

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);  // Clear the table before adding new results

        if (file.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(file))) {
                String line;
                StringBuilder record = new StringBuilder();
                boolean found = false;

                while ((line = br.readLine()) != null) {
                    record.append(line).append("\n");
                    if (line.equals("-------------------------------")) {
                        String[] data = record.toString().split("\n");
                        String customerId = data[0].split(": ")[1].trim();  // Assuming Customer ID is on the first line

                        if (customerId.equals(searchUserId)) {
                            found = true;

                            // Extract relevant data
                            String hallId = data[5].split(": ")[1].trim();      // Assuming Hall ID is on line 6
                            String hallType = data[6].split(": ")[1].trim();    // Assuming Hall Type is on line 7
                            String bookingDate = data[4].split(": ")[1].trim(); // Assuming Booking Date is on line 5

                            // Add data to the table
                            model.addRow(new Object[]{hallId, hallType, bookingDate});
                        }
                        record.setLength(0); // Clear for next record
                    }
                }

                if (!found) {
                    JOptionPane.showMessageDialog(this, "No bookings found for this user ID.", "Search Result", JOptionPane.INFORMATION_MESSAGE);
                }

            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error reading from BookedHall.txt", "File Error", JOptionPane.ERROR_MESSAGE);
                e.printStackTrace();
            }
        } else {
            JOptionPane.showMessageDialog(this, "BookedHall.txt not found!", "File Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int selectedRow = jTable1.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a hall from the table.", "No Hall Selected", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Step 2: Get the data from the selected row (Hall ID, Hall Type, Booking Date)
    String hallId = jTable1.getValueAt(selectedRow, 0).toString();  // Assuming Hall ID is in column 0
    String hallType = jTable1.getValueAt(selectedRow, 1).toString();  // Assuming Hall Type is in column 1
    String bookingDate = jTable1.getValueAt(selectedRow, 2).toString();  // Assuming Booking Date is in column 2

    // Step 3: Get the feedback written by the customer
    String feedback = Feedback.getText().trim();
    if (feedback.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please write your feedback.", "No Feedback", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Step 4: Write the selected hall details and feedback to Feedback.txt
    File feedbackFile = new File("Feedback.txt");
    try (FileWriter fw = new FileWriter(feedbackFile, true); // true to append to the file
         BufferedWriter bw = new BufferedWriter(fw)) {
        
        bw.write("Hall ID: " + hallId);
        bw.newLine();
        bw.write("Hall Type: " + hallType);
        bw.newLine();
        bw.write("Booking Date: " + bookingDate);
        bw.newLine();
        bw.write("Feedback: " + feedback);
        bw.newLine();
        bw.write("-------------------------------");
        bw.newLine();

        // Step 5: Show success message
        JOptionPane.showMessageDialog(this, "Your feedback has been saved successfully!", "Feedback Saved", JOptionPane.INFORMATION_MESSAGE);

        // Clear the feedback text field after saving
        Feedback.setText("");

    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error while saving feedback: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
        e.printStackTrace(); // For debugging purposes
    }
      this.dispose(); // 
        new MainCustomer().setVisible(true); 
    }//GEN-LAST:event_jButton2ActionPerformed

