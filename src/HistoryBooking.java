    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        String searchCustomerId = Usercheck.getText().trim();  // Get the customer ID from the text field
        File file = new File("HistoryBooking.txt");

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);  // Clear the table before displaying new results

        if (file.exists()) {
            try (BufferedReader br = new BufferedReader(new FileReader(file))) {
                String line;
                StringBuilder record = new StringBuilder();
                boolean found = false;

                while ((line = br.readLine()) != null) {
                    record.append(line).append("\n");
                    if (line.equals("-------------------------------")) {
                        String[] data = record.toString().split("\n");
                        String customerId = data[0].split(": ")[1].trim(); // Change this line to extract Customer ID

                        // Debugging output
                        System.out.println("Checking customer ID: " + customerId);

                        if (customerId.equals(searchCustomerId)) {
                            found = true;

                            // Prepare data for the table
                            Object[] rowData = new Object[]{
                                customerId,                                 // User ID
                                data[1].split(": ")[1].trim(),              // Name
                                data[2].split(": ")[1].trim(),              // Email
                                data[3].split(": ")[1].trim(),              // Phone
                                data[4].split(": ")[1].trim(),              // Date
                                data[5].split(": ")[1].trim(),              // Hall ID
                                data[6].split(": ")[1].trim(),              // Hall Type
                                data[7].split(": ")[1].trim(),              // Booking Rate
                                data[8].split(": ")[1].trim(),              // Capacity
                                data[9].split(": ")[1].trim(),              // Remarks
                                data[10].split(": ")[1].trim()               // Payment Method
                            };
                            model.addRow(rowData);
                        }
                        record.setLength(0); // Clear for next record
                    }
                }

                if (!found) {
                    JOptionPane.showMessageDialog(this, "No bookings found for this customer ID.", "Search Result", JOptionPane.INFORMATION_MESSAGE);
                }

            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error reading from BookedHall.txt", "File Error", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "BookedHall.txt not found!", "File Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton4ActionPerformed

