    // Method to load customer issues without status
public List<CustomerIssue> loadCustomerIssues() {
    List<CustomerIssue> issues = new ArrayList<>();
    try (BufferedReader reader = new BufferedReader(new FileReader("customer_issues.txt"))) {
        String line;
        while ((line = reader.readLine()) != null) {
            String[] parts = line.split(" \\| ");
            String issueID = parts[0].split(": ")[1];
            String hall = parts[1].split(": ")[1];
            String customer = parts[2].split(": ")[1];
            String issue = parts[3].split(": ")[1];
            String dateReported = parts[4].split(": ")[1];

            issues.add(new CustomerIssue(issueID, hall, customer, issue, dateReported));
        }
    } catch (IOException e) {
        e.printStackTrace();
    }
    return issues;
}
    
// Method to load issue statuses from issues_data.txt
public Map<String, String> loadIssueStatuses() {
    Map<String, String> statusMap = new HashMap<>();
    try (BufferedReader reader = new BufferedReader(new FileReader("issues_data.txt"))) {
        String line;
        while ((line = reader.readLine()) != null) {
            String[] parts = line.split(" \\| ");
            String issueID = parts[0].split(": ")[1];
            String status = parts[1].split(": ")[1]; // Adjust based on actual format
            
            statusMap.put(issueID, status); // Store status with issueID as key
        }
    } catch (IOException e) {
        e.printStackTrace();
    }
    return statusMap;
}

// Method to combine both data sets
public List<CustomerIssue> getCombinedCustomerIssues() {
    List<CustomerIssue> issues = loadCustomerIssues();
    Map<String, String> statusMap = loadIssueStatuses();

    // Assign statuses to customer issues
    for (CustomerIssue issue : issues) {
        String status = statusMap.get(issue.getIssueID()); // Get status based on issueID
        if (status != null) {
            issue.setStatus(status); // Set the status if found
        }
    }
    
    return issues; // Return the list with updated statuses
}

public void displayIssues() {
    List<CustomerIssue> issues = loadCustomerIssues();
    Map<String, String> statusMap = loadIssueStatuses();

    // Prepare table data
    DefaultTableModel tableModel = new DefaultTableModel(new String[]{"Issue ID", "Hall", "Customer", "Issue", "Date Reported", "Status"}, 0);

    if (issues.isEmpty()) {
        JOptionPane.showMessageDialog(null, "No customer issues found.", "Information", JOptionPane.INFORMATION_MESSAGE);
        return; // Exit if there are no issues to display
    }

    for (CustomerIssue issue : issues) {
        String status = statusMap.getOrDefault(issue.getIssueID(), "Unknown");
        Object[] rowData = {
            issue.getIssueID(),
            issue.getHall(),
            issue.getCustomer(),
            issue.getIssue(),
            issue.getDateReported(),
            status
        };
        tableModel.addRow(rowData);
    }

    // Assuming you have a JTable named issuesTable
    issuesTable.setModel(tableModel);
}


    
