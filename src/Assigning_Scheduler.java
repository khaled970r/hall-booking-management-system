    // Method to generate the next Assignment ID
    private String generateAssignmentID() {
        // Load the last AssignmentID from the file or keep track in memory
        // For demonstration, we'll simply increment from a hardcoded value
        // In a real application, you should read this from the file
        return String.format("%03d", 1); // Example: returns "001"
    }

    private void saveAssignment() {
        String assignmentID = generateAssignmentID(); // Generate Assignment ID
        String scheduler = schedulerName.getText();
        String issueID = issueIDTextBox.getText();
        //String startDate = new SimpleDateFormat("yyyy-MM-dd").format(startDateChooser.getDate());
        //String endDate = new SimpleDateFormat("yyyy-MM-dd").format(jDateChooser2.getDate());
        String startDate="";
        String endDate="";
        String remarks = remarksTextArea.getText();

        // Format the string to save
        String dataToSave = String.format("AssignmentID: %s | Scheduler: %s | IssueID: %s | Start Date: %s | End Date: %s | Remarks: %s",
                assignmentID, scheduler, issueID, startDate, endDate, remarks);

        try (BufferedWriter writer = new BufferedWriter(new FileWriter("scheduler_assignment.txt", true))) {
            writer.write(dataToSave);
            writer.newLine(); // Move to the next line for the next entry
            JOptionPane.showMessageDialog(null, "Assignment saved successfully!");
        } catch (IOException e) {
            e.printStackTrace(); // Handle the exception
            JOptionPane.showMessageDialog(null, "Error saving assignment.");
        }

        // Optionally, clear the input fields after saving
        clearInputFields();
    }

    private void clearInputFields() {
        schedulerName.setText("");
        issueIDTextBox.setText("");
        //startDateChooser.setDate(null);
        //jDateChooser2.setDate(null);
        remarksTextArea.setText("");
    }
    
    
    
