    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                        
   int selectedRow = jTable1.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a booking from the table to cancel.", "No Booking Selected", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Step 2: Retrieve booking details from the selected row
    String bookingDate = jTable1.getValueAt(selectedRow, 4).toString().trim(); // Booking date
    String hallId = jTable1.getValueAt(selectedRow, 5).toString().trim();      // Hall ID
    String customerName = jTable1.getValueAt(selectedRow, 1).toString().trim(); // Customer Name

    // Step 3: Confirm cancellation with the user
    int response = JOptionPane.showConfirmDialog(this, "Are you sure you want to cancel this booking?", "Confirm Cancellation", JOptionPane.YES_NO_OPTION);
    if (response != JOptionPane.YES_OPTION) {
        return; // User chose not to cancel
    }

    // Step 4: Validate the booking date
    DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
    LocalDate today = LocalDate.now();

    try {
        LocalDate bookingLocalDate = LocalDate.parse(bookingDate, formatter);
        long daysUntilBooking = ChronoUnit.DAYS.between(today, bookingLocalDate);

        if (daysUntilBooking <= 3) {
            JOptionPane.showMessageDialog(this, "You cannot cancel a booking that is 3 days or less away.", "Cancellation Not Allowed", JOptionPane.WARNING_MESSAGE);
            return; // Cannot cancel
        }

        // Step 5: Define file path
        File bookedFile = new File("BookedHall.txt");

        // Step 6: Read BookedHall.txt and filter out the booking to cancel
        StringBuilder updatedBookings = new StringBuilder();
        boolean bookingFound = false;

        // Variables to hold current booking details
        String currentCustomerUser = "";
        String currentCustomerName = "";
        String currentCustomerEmail = "";
        String currentCustomerPhone = "";
        String currentBookingDate = "";
        String currentHallId = "";
        String currentHallType = "";
        String currentBookingRate = "";
        String currentCapacity = "";
        String currentRemarks = "";
        String currentPaymentMethod = "";

        try (BufferedReader reader = new BufferedReader(new FileReader(bookedFile))) {
            String line;
            while ((line = reader.readLine()) != null) {
                if (line.startsWith("Customer User: ")) {
                    currentCustomerUser = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Customer Name: ")) {
                    currentCustomerName = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Customer Email: ")) {
                    currentCustomerEmail = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Customer Phone: ")) {
                    currentCustomerPhone = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Booking Date: ")) {
                    currentBookingDate = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Hall ID: ")) {
                    currentHallId = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Hall Type: ")) {
                    currentHallType = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Booking Rate: ")) {
                    currentBookingRate = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Capacity: ")) {
                    currentCapacity = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Remarks: ")) {
                    currentRemarks = line.split(": ", 2)[1].trim();
                } else if (line.startsWith("Payment Method: ")) {
                    currentPaymentMethod = line.split(": ", 2)[1].trim();
                }

                if (line.equals("-------------------------------")) {
                    // Check if this is the booking to cancel
                    if (currentCustomerName.equals(customerName) && currentHallId.equals(hallId) && currentBookingDate.equals(bookingDate)) {
                        bookingFound = true;
                        // Do not append this booking to updatedBookings to effectively delete it
                    } else {
                        // Retain the booking in BookedHall.txt
                        updatedBookings.append("Customer User: ").append(currentCustomerUser).append("\n")
                                      .append("Customer Name: ").append(currentCustomerName).append("\n")
                                      .append("Customer Email: ").append(currentCustomerEmail).append("\n")
                                      .append("Customer Phone: ").append(currentCustomerPhone).append("\n")
                                      .append("Booking Date: ").append(currentBookingDate).append("\n")
                                      .append("Hall ID: ").append(currentHallId).append("\n")
                                      .append("Hall Type: ").append(currentHallType).append("\n")
                                      .append("Booking Rate: ").append(currentBookingRate).append("\n")
                                      .append("Capacity: ").append(currentCapacity).append("\n")
                                      .append("Remarks: ").append(currentRemarks).append("\n")
                                      .append("Payment Method: ").append(currentPaymentMethod).append("\n")
                                      .append("-------------------------------\n");
                    }

                    // Reset current booking details
                    currentCustomerUser = "";
                    currentCustomerName = "";
                    currentCustomerEmail = "";
                    currentCustomerPhone = "";
                    currentBookingDate = "";
                    currentHallId = "";
                    currentHallType = "";
                    currentBookingRate = "";
                    currentCapacity = "";
                    currentRemarks = "";
                    currentPaymentMethod = "";
                }
            }
        }

        if (!bookingFound) {
            JOptionPane.showMessageDialog(this, "Booking not found!", "Cancellation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Step 7: Overwrite BookedHall.txt with updated bookings (excluding the canceled one)
        try (PrintWriter bookedWriter = new PrintWriter(new FileWriter(bookedFile, false))) {
            bookedWriter.print(updatedBookings.toString());
        }

        JOptionPane.showMessageDialog(this, "Booking cancelled successfully.", "Cancellation Success", JOptionPane.INFORMATION_MESSAGE);

        // Step 8: Remove the row from the table after cancellation
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.removeRow(selectedRow);

    } catch (DateTimeParseException e) {
        JOptionPane.showMessageDialog(this, "Invalid date format. Please use dd/MM/yyyy.", "Date Format Error", JOptionPane.ERROR_MESSAGE);
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error while processing cancellation: " + e.getMessage(), "File Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
    String searchCustomerId = Usercheck.getText().trim();  // Get the customer ID from the text field
    File file = new File("BookedHall.txt");

    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);  // Clear the table before displaying new results

    if (file.exists()) {
        try (BufferedReader br = new BufferedReader(new FileReader(file))) {
            String line;
            StringBuilder record = new StringBuilder();
            boolean found = false;

            while ((line = br.readLine()) != null) {
                record.append(line).append("\n");
                if (line.equals("-------------------------------")) {
                    String[] data = record.toString().split("\n");
                    String customerId = data[0].split(": ")[1].trim(); // Change this line to extract Customer ID

                    // Debugging output
                    System.out.println("Checking customer ID: " + customerId);

                    if (customerId.equals(searchCustomerId)) {
                        found = true;

                        // Prepare data for the table
                        Object[] rowData = new Object[]{
                            customerId,                                 // User ID
                            data[1].split(": ")[1].trim(),              // Name
                            data[2].split(": ")[1].trim(),              // Email
                            data[3].split(": ")[1].trim(),              // Phone
                            data[4].split(": ")[1].trim(),              // Date
                            data[5].split(": ")[1].trim(),              // Hall ID
                            data[6].split(": ")[1].trim(),              // Hall Type
                            data[7].split(": ")[1].trim(),              // Booking Rate
                            data[8].split(": ")[1].trim(),              // Capacity
                            data[9].split(": ")[1].trim(),              // Remarks
                            data[10].split(": ")[1].trim()               // Payment Method
                        };
                        model.addRow(rowData);
                    }
                    record.setLength(0); // Clear for next record
                }
            }

            if (!found) {
                JOptionPane.showMessageDialog(this, "No bookings found for this customer ID.", "Search Result", JOptionPane.INFORMATION_MESSAGE);
            }

        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error reading from BookedHall.txt", "File Error", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "BookedHall.txt not found!", "File Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton4ActionPerformed

