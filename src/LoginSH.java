    private void LoginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LoginButtonActionPerformed
        // TODO add your handling code here:
        // Get entered username and password
        String enteredUsername = UsernameField.getText();
        String enteredPassword = new String(jPasswordField1.getPassword());

        // Print the current working directory for debugging
        System.out.println("Current working directory: " + System.getProperty("user.dir"));

        // Specify the path to your credentials file
        String filePath = "UserPass.txt";
        //String filePath = "C:\\path\\to\\your\\project\\UserPass.txt";

        try (BufferedReader reader = new BufferedReader(new FileReader(filePath))) {
            String line;
            boolean validCredentials = false;

            // Read the file line by line and check for valid credentials
            while ((line = reader.readLine()) != null) {
                String[] credentials = line.split(" ");
                String fileUsername = credentials[0];
                String filePassword = credentials[1];

                if (enteredUsername.equals(fileUsername) && enteredPassword.equals(filePassword)) {
                    validCredentials = true;
                    break;
                }
            }

            if (validCredentials) {
                // Navigate to HomePage if the credentials are valid
                HomePage homePage = new HomePage();
                homePage.setVisible(true);
                this.dispose();  // Close the login window
            } else {
                // Show error message if credentials are invalid
                JOptionPane.showMessageDialog(this, "Invalid username or password", "Login Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (IOException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error reading credentials file", "File Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_LoginButtonActionPerformed

