       // Method to display the filtered sales in the table
private void displaySales(List<Sale> filteredSales) {
    // Assuming you have a JTable called 'salesTable'
    DefaultTableModel tableModel = (DefaultTableModel) salesTable.getModel();

    // Clear the existing table data
    tableModel.setRowCount(0);

    // Loop through the filtered sales and add each row to the table
    for (Sale sale : filteredSales) {
        Object[] rowData = {
            sale.getBookingID(),
            new SimpleDateFormat("yyyy-MM-dd").format(sale.getDate()),
            sale.getHall(),
            sale.getAmount(),
            sale.getCustomer()
        };

        tableModel.addRow(rowData);
    }
}
    
